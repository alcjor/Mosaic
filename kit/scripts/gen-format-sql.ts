/**
 * Write `kit/src/format-sql.ts` from `spec/format.sql`, the schema the kit compares a file's
 * schema against (Specification 0.1, sections 3.1 and 3.8). The kit runs in a page and in
 * Node, so it carries the normative file as a string, without the comment lines between
 * statements: SQLite keeps only each statement's own text in `sqlite_schema`, and those
 * comments hold examples that do not belong in domain-neutral code (principle 9).
 * `test/open.test.ts` checks that both texts make the same schema.
 *
 *     bun kit/scripts/gen-format-sql.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const spec = fileURLToPath(new URL("../../spec/format.sql", import.meta.url));
const out = fileURLToPath(new URL("../src/format-sql.ts", import.meta.url));
const sql = readFileSync(spec, "utf8")
  .split("\n")
  .filter((line) => !line.startsWith("--"))
  .join("\n");
const body = [
  "// Generated by kit/scripts/gen-format-sql.ts from spec/format.sql; do not edit.",
  "",
  "/** `spec/format.sql` without its comment lines: the schema of tesserae and mosaics (section 3.1). */",
  `export const FORMAT_SQL: string = ${JSON.stringify(sql)};`,
  "",
].join("\n");
writeFileSync(out, body, "utf8");
console.log(`wrote ${out}`);
