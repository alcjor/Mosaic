"""The toy profile: a bicycle workshop with parts, suppliers and two HTML documents.

It feeds the core's genericity tests (CORE-06, MOCK-05): nothing in it is about space.
Part names are multi-word surface forms, so it also exercises multi-token matching.
"""

from __future__ import annotations

import random
from collections import defaultdict
from collections.abc import Mapping, Sequence
from pathlib import Path

from mosaic_mock.engine.generate import DefectInjector, RenderContext, Renderer, SizeSpec
from mosaic_mock.engine.model import Artifact, Document, Para, RawFile, Section, Table, TableFile
from mosaic_mock.engine.rng import Rng
from mosaic_mock.engine.text import Ref, Text
from mosaic_mock.engine.truth import Placement, XrefTruth
from mosaic_mock.engine.world import Item, World

SUPPLIERS = (
    "Northwind Cycles",
    "Harbour Components",
    "Ridge Works",
    "Alder & Sons",
    "Kestrel Supply",
)
PART_NAMES = (
    "brake lever",
    "chain ring",
    "spoke nipple",
    "hub bearing",
    "seat clamp",
    "bottle cage",
    "brake pad",
    "rim tape",
    "valve cap",
    "cable housing",
    "derailleur hanger",
    "crank arm",
    "pedal axle",
    "headset spacer",
    "saddle rail",
    "bar tape",
    "chain pin",
    "cassette lockring",
    "fork crown",
    "dropout insert",
    "tyre bead",
    "mudguard stay",
    "kickstand bolt",
    "bell clamp",
    "reflector bracket",
    "lamp mount",
    "cleat plate",
    "toe strap",
    "jockey wheel",
    "pump head",
)
ASSEMBLIES = ("Front wheel", "Drive train", "Cockpit", "Frame fittings", "Accessories")
CATALOGUE = "docs/catalogue.html"
ASSEMBLY = "docs/assembly.html"


class ToyRenderer:
    name = "toy"

    def render(self, ctx: RenderContext) -> Sequence[Artifact]:
        w = ctx.world
        parts = w.of_type("Part")
        suppliers = w.of_type("Supplier")
        r = ctx.rng.stream("toy:text")

        def pid(p: Item, role: str) -> Ref:
            return Ref(p.ref, p.key, role, "exact", "id")

        def pname(p: Item, role: str) -> Ref:
            return Ref(p.ref, p.attrs["part_name"], role, "exact", "mn")

        cat = Document(CATALOGUE.removesuffix(".html"), ("html",), "Workshop parts catalogue")
        cat.front.append(Para(["Parts stocked by the workshop, by supplier."]))
        by_sup: dict[str, list[Item]] = defaultdict(list)
        for p in parts:
            by_sup[p.attrs["supplier"]].append(p)
        children = []
        for k, s in enumerate(suppliers, 1):
            ps = by_sup[s.key]
            intro: Text = [f"{s.attrs['supplier_name']} supplies "]
            for i, p in enumerate(ps[:2]):
                intro += [
                    " and " if i else "",
                    "the ",
                    pname(p, "mentions"),
                    " (",
                    pid(p, "mentions"),
                    ")",
                ]
            intro.append(", among others." if len(ps) > 2 else ".")
            rows = [
                [[pid(p, "describes")], [pname(p, "describes")], [str(r.randrange(2, 60))]]
                for p in ps
            ]
            children.append(
                Section(
                    f"1.{k}",
                    [s.attrs["supplier_name"]],
                    2,
                    [Para(intro), Table(["Part", "Name", "Stock"], rows)],
                )
            )
        cat.sections = [Section("1", ["Parts by supplier"], 1, [], children)]

        asm = Document(ASSEMBLY.removesuffix(".html"), ("html",), "Assembly guide")
        asm.front.append(Para(["Fit the parts in the order given in each section."]))
        secs = []
        chunk = max(1, len(parts) // len(ASSEMBLIES))
        for k, title in enumerate(ASSEMBLIES):
            ps = parts[k * chunk : (k + 1) * chunk]
            blocks = []
            for p in ps:
                blocks.append(
                    Para(
                        [
                            "Fit the ",
                            pname(p, "mentions"),
                            " (",
                            pid(p, "mentions"),
                            ") and check it by hand.",
                        ],
                        "bullet",
                    )
                )
            secs.append(Section(str(k + 1), [title], 1, blocks))
        asm.sections = secs

        project = """# Toy workshop, generated by mosaic-mock. Everything here is invented.
pack: _toy
project: TOY-WORKSHOP
output: build/toy.mosaic.sqlite
sources:
  parts: {path: data/parts.csv}
  suppliers: {path: data/suppliers.csv}
  catalogue: {path: docs/catalogue.html}
  assembly: {path: docs/assembly.html}
"""
        return [
            TableFile(
                "data/suppliers.csv",
                "Supplier",
                [[s.key, s.attrs["supplier_name"]] for s in suppliers],
                ",",
                ["supplier_id", "supplier_name"],
            ),
            TableFile(
                "data/parts.csv",
                "Part",
                [[p.key, p.attrs["part_name"], p.attrs["supplier"]] for p in parts],
                ",",
                ["part_id", "part_name", "supplier"],
            ),
            cat,
            asm,
            RawFile("mosaic.yaml", project.encode()),
        ]


class ToyProfile:
    name = "toy"
    sizes: Mapping[str, SizeSpec] = {
        "small": SizeSpec("small", {"parts": 20, "suppliers": 4}),
        "medium": SizeSpec("medium", {"parts": 30, "suppliers": 5}),
    }
    default_defects: Sequence[str] = ()

    def build_world(self, rng: Rng, size: SizeSpec) -> World:
        w = World()
        r: random.Random = rng.stream("toy:world")
        sups = [
            w.add(
                Item(
                    "Supplier",
                    f"S{i + 1:02d}",
                    {"supplier_id": f"S{i + 1:02d}", "supplier_name": SUPPLIERS[i]},
                )
            )
            for i in range(min(size["suppliers"], len(SUPPLIERS)))
        ]
        names = list(PART_NAMES[: size["parts"]])
        for n in names:
            w.naming.register(n, guard=False)
        for i, name in enumerate(names):
            key = w.naming.numbered_id("P-", r, digits=3)
            sup = sups[i % len(sups)]
            part = w.add(
                Item("Part", key, {"part_id": key, "part_name": name, "supplier": sup.key})
            )
            w.link("supplier", part, sup)
        return w

    def renderers(self) -> Sequence[Renderer]:
        return [ToyRenderer()]

    def defect_injectors(self) -> Mapping[str, DefectInjector]:
        return {}

    def template_dir(self) -> Path:
        return Path(__file__).parent

    def xrefs(self, placements: Sequence[Placement], ctx: RenderContext) -> list[XrefTruth]:
        """``uses_part_from``: assembly section → catalogue section that describes the part."""
        desc: dict[str, set[str]] = defaultdict(set)
        for p in placements:
            if p.file == CATALOGUE and p.role == "describes" and p.match == "exact":
                desc[p.item].add(p.scope)
        found = {
            XrefTruth("uses_part_from", p.file, p.scope, CATALOGUE, s)
            for p in placements
            if p.file == ASSEMBLY and p.match == "exact"
            for s in desc.get(p.item, ())
        }
        return sorted(found, key=lambda x: (x.from_scope, x.to_scope))
