def key_of(table: str, attrs: dict[str, str]) -> str:
    return "|".join(attrs.get(c, "") for c in KEYS[table])


def row_of(table: str, attrs: dict[str, str]) -> list[str]:
    cols = [c for c, _ in COLUMNS[table]] + CUSTOM.get(table, [])
    return [attrs.get(c, "") for c in cols]
