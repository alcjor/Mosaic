class ProjectRenderer:
    """The ready ``mosaic.yaml`` for the spacecraft pack (MOCK-16)."""

    name = "project"

    def render(self, ctx: RenderContext) -> Sequence[Artifact]:
        m = mission(ctx)
        maps = "\n".join(
            f"    - {{from: {{source: code, path_glob: src/{s.code.lower()}_app.c}}, "
            f"to: {{source: sum, heading_regex: '^{FIRST_APP_CHAPTER + i} {s.spec.name} "
            f"application'}}}}"
            for i, s in enumerate(m.subs)
        )
        text = f"""# DEMOSAT-1 mock mission, generated by mosaic-mock {__version__}.
# Everything here is invented. Build it with: mosaic build mosaic.yaml
pack: spacecraft
project: DEMOSAT-1
output: build/demosat-1.mosaic.sqlite
sources:
  srdb: {{path: srdb/, options: {{icd_issue: "7.0", custom_columns: {{pcf: [PCF_LDESCR]}}}}}}
  icd: {{path: {ICD}}}
  sum: {{path: [{SUM}, sum/sum.pdf]}}
  code: {{path: {CODE_ROOT}, include: ["**/*.c", "**/*.h"]}}
  fops: {{path: fops/, include: ["**/*.py"]}}
xref_maps:
  code-file-documented-in:
{maps}
"""
        return [RawFile("mosaic.yaml", text.encode())]


class SpacecraftProfile:
    name = "spacecraft"
    sizes: Mapping[str, SizeSpec] = SIZES
    default_defects: Sequence[str] = ()

    def build_world(self, rng: Rng, size: SizeSpec) -> World:
        return world_mod.build_world(rng, size)

    def renderers(self) -> Sequence[Renderer]:
        return [
            SrdbRenderer(),
            IcdRenderer(),
            ManualRenderer(),
            CodeRenderer(),
            FopRenderer(),
            ProjectRenderer(),
        ]

    def defect_injectors(self) -> Mapping[str, DefectInjector]:
        return {}

    def template_dir(self) -> Path:
        return Path(__file__).parent / "templates"

    def xrefs(self, placements: Sequence[Placement], ctx: RenderContext) -> list[XrefTruth]:
        """Cross-references the pack's rules must find (02 § 5), from exact placements."""
        exact = [p for p in placements if p.match == "exact"]

        def scopes(pred, roles: set[str]) -> dict[str, set[tuple[str, str]]]:
            out: dict[str, set[tuple[str, str]]] = defaultdict(set)
            for p in exact:
                if pred(p.file) and p.role in roles:
                    out[p.item].add((p.file, p.scope))
            return out

        def is_fop(f: str) -> bool:
            return f.startswith("fops/")

        def is_code(f: str) -> bool:
            return f.startswith(CODE_ROOT)

        fop_steps = {
            item: {s for s in v if s[1].startswith("step=")}
            for item, v in scopes(is_fop, {"sends", "reads"}).items()
        }
        fop_sends = {
            item: {s for s in v if s[1].startswith("step=")}
            for item, v in scopes(is_fop, {"sends"}).items()
        }
        sum_desc = scopes(lambda f: f == SUM, {"describes"})
        icd_desc = scopes(lambda f: f == ICD, {"describes"})
        handled = scopes(is_code, {"handles"})

        found: set[XrefTruth] = set()

        def via_entity(kind: str, src: dict, dst: dict) -> None:
            for item, froms in src.items():
                for f in froms:
                    for t in dst.get(item, ()):
                        found.add(XrefTruth(kind, f[0], f[1], t[0], t[1]))

        via_entity("described_in", fop_steps, sum_desc)
        via_entity("defined_in", fop_steps, icd_desc)
        via_entity("handled_by", fop_sends, handled)
        via_entity("see_also", sum_desc, icd_desc)

        # code-file-documented-in: explicit map for each application file, else entity fallback.
        m = mission(ctx)
        explicit = {
            f"{CODE_ROOT}src/{s.code.lower()}_app.c": f"section={FIRST_APP_CHAPTER + i}"
            for i, s in enumerate(m.subs)
        }
        by_file: dict[str, set[str]] = defaultdict(set)
        for p in exact:
            if is_code(p.file) and p.role in ("handles", "defines_id"):
                by_file[p.file].add(p.item)
        code_files = {p.file for p in placements if is_code(p.file)}
        section_items: dict[str, set[str]] = defaultdict(set)
        for item, places in sum_desc.items():
            for _, scope in places:
                section_items[scope].add(item)
        for f in sorted(code_files):
            if f in explicit:
                found.add(XrefTruth("documented_in", f, "file", SUM, explicit[f]))
                continue
            for scope, items in section_items.items():
                if len(items & by_file[f]) >= 2:
                    found.add(XrefTruth("documented_in", f, "file", SUM, scope))
        return sorted(
            found, key=lambda x: (x.type, x.from_file, x.from_scope, x.to_file, x.to_scope)
        )
